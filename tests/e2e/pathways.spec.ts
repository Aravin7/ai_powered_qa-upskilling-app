import { mkdir } from 'node:fs/promises';
import { test, expect } from '@playwright/test';
import { encode } from 'next-auth/jwt';
import { PrismaClient } from '../../src/generated/prisma/client';
import { PrismaPg } from '@prisma/adapter-pg';
import { catalogue } from '../../src/lib/catalogue';
import { POLICY_VERSION } from '../../src/lib/domain';
import { generateRoadmap } from '../../src/lib/ai-operations';

test.beforeAll(async({request})=>{
 if(process.env.RUN_AUTHENTICATED_E2E!=='true')return;
 test.setTimeout(120000);
 expect((await request.get('/api/me')).status()).toBe(401);
 expect((await request.get('/')).status()).toBe(200);
});

test('PX-E2E: explore/select QA direction, research mock resources, reload, and preserve the old plan',async({page,context,request})=>{
 test.skip(process.env.RUN_AUTHENTICATED_E2E!=='true','Requires dedicated test database and test-signed identity; real Google OAuth is not tested.');
 test.setTimeout(120000);
 expect((await request.get('/api/auth/providers')).status()).toBe(200);
 const url=process.env.TEST_DATABASE_URL!;
 if(!/^qa_pathways_/.test(new URL(url).pathname.slice(1)))throw new Error('Use only a dedicated qa_pathways_* test database.');
 const client=new PrismaClient({adapter:new PrismaPg({connectionString:url,max:3})});
 const email=`pathway-browser-${crypto.randomUUID()}@example.invalid`;const budgetId=process.env.AI_BUDGET_ID!;
 const evidence='docs/evidence/2026-10-17-resource-previews';
 try{
  await client.invitation.create({data:{email}});
  const user=await client.user.create({data:{email,googleSubject:crypto.randomUUID(),name:'Synthetic QA Learner',profile:{create:{currentRole:'QA Engineer',yearsExperience:7,hoursPerWeek:5,confirmed:true,inventoryConfirmed:true,planningRevision:2}},skills:{create:catalogue.skills.slice(0,3).map(skill=>({key:`id:${skill.id}`,canonicalSkillId:skill.id,label:skill.label,catalogueVersion:catalogue.version}))},consents:{create:{purpose:'roadmap_generation',granted:true,policyVersion:POLICY_VERSION}}}});
  await client.catalogueRevision.upsert({where:{id:'active'},create:{id:'active',version:catalogue.version},update:{}});
  await client.fundingBudget.create({data:{id:budgetId,mode:'mock',currency:'MOCK',pricingVersion:'mock-v1',ceiling:30,expiresAt:new Date(Date.now()+3600000)}});
  const claims={id:user.id,email,sessionVersion:0};
  const initial=await generateRoadmap(client,claims,{operationKey:crypto.randomUUID(),expectedPlanningRevision:2,expectedCatalogueVersion:catalogue.version,introductoryPlanAcknowledged:false});
  const planId=initial.state.roadmap!.id;await client.roadmapTask.updateMany({where:{roadmapId:planId},data:{completed:true}});
  const token=await encode({secret:process.env.NEXTAUTH_SECRET!,token:{uid:user.id,email,name:user.name,sessionVersion:0},maxAge:3600});
  await context.addCookies([{name:'next-auth.session-token',value:token,url:`http://127.0.0.1:${process.env.E2E_PORT??'3000'}`,httpOnly:true,sameSite:'Lax'}]);
  expect((await page.request.get('/api/me')).status()).toBe(200);
  await page.goto('/');await page.getByRole('button',{name:'Explore directions',exact:true}).click();
  for(const label of ['AI-assisted testing','Testing AI applications','AI security and safety','Automation and CI/CD','Performance and reliability'])await page.getByLabel(label,{exact:true}).check();
  await page.getByLabel('Preferred work',{exact:true}).selectOption('automation');
  await page.getByLabel('Coding preference',{exact:true}).selectOption('some');
  const savedPreferences=page.waitForResponse(response=>response.url().endsWith('/api/pathways/preferences')&&response.request().method()==='PUT');
  await page.getByRole('button',{name:'Save exploration preferences'}).click();expect((await savedPreferences).status()).toBe(200);
  await expect(page.getByRole('status').filter({hasText:'Exploration preferences saved.'})).toBeVisible();
  const generated=page.waitForResponse(response=>response.url().endsWith('/api/pathways/suggest'));
  await page.getByRole('button',{name:'Suggest mock QA directions'}).click();expect((await generated).status()).toBe(200);
  await expect(page.getByRole('button',{name:/^Save direction of interest:/})).toHaveCount(3);
  await mkdir(evidence,{recursive:true});await page.screenshot({path:`${evidence}/01-provisional-suggestions.png`,fullPage:true});
  await page.getByRole('button',{name:'Explore more suggestions'}).click();await expect(page.getByRole('button',{name:/^Save direction of interest:/})).toHaveCount(5);
  const chosen=page.waitForResponse(response=>response.url().endsWith('/api/pathways/select'));
  await page.getByRole('button',{name:/^Save direction of interest:/}).first().click();expect((await chosen).status()).toBe(200);
  await expect(page.getByRole('button',{name:'Clear provisional direction'})).toBeVisible();
  await page.reload();await page.getByRole('button',{name:'Explore directions',exact:true}).click();
  await expect(page.getByRole('button',{name:'Clear provisional direction'})).toBeVisible();await page.screenshot({path:`${evidence}/02-saved-direction.png`,fullPage:true});
  const resourcePanel=page.getByRole('region',{name:'Mock learning resource previews'});
  await resourcePanel.getByText('Test automation',{exact:true}).click();
  const researched=page.waitForResponse(response=>response.url().endsWith('/api/pathways/resources'));
  await page.getByRole('button',{name:'Preview mock resources: Test automation',exact:true}).click();
  expect((await researched).status()).toBe(200);
  await expect(page.getByRole('region',{name:'Saved mock resources: Test automation'})).toBeVisible();
  const resourceOp=await client.aIOperation.findFirstOrThrow({where:{userId:user.id,kind:'resource_research'}});expect(resourceOp.attempts).toBe(2);
  await page.reload();await page.getByRole('button',{name:'Explore directions',exact:true}).click();
  await page.getByRole('region',{name:'Mock learning resource previews'}).getByText('Test automation',{exact:true}).click();
  const savedPair=page.getByRole('region',{name:'Saved mock resources: Test automation'});
  await expect(savedPair.getByRole('heading',{name:'Documentation fixture'})).toBeVisible();
  await expect(savedPair.getByRole('heading',{name:'Supporting lesson fixture'})).toBeVisible();
  await expect(savedPair.getByRole('link')).toHaveCount(0);
  await page.screenshot({path:`${evidence}/04-resource-preview-reloaded.png`,fullPage:true});
  const state=(await (await page.request.get('/api/me')).json()).data;
  const attempts=await client.aIAttempt.count({where:{operation:{userId:user.id}}});
  const budget=await client.fundingBudget.findUniqueOrThrow({where:{id:budgetId}});
  await client.fundingBudget.update({where:{id:budgetId},data:{ceiling:budget.reserved}});
  const deniedPreview=page.waitForResponse(response=>response.url().endsWith('/api/pathways/resources'));
  await page.getByRole('button',{name:'Preview mock resources: Test automation',exact:true}).click();
  const deniedResponse=await deniedPreview;expect(deniedResponse.status()).toBe(503);
  expect((await deniedResponse.json()).code).toBe('FUNDING_STOP');
  await expect(page.getByRole('alert').filter({hasText:'Shared funding is missing, expired or exhausted. No request was dispatched.'})).toBeVisible();
  await expect(savedPair).toBeVisible();
  await page.screenshot({path:`${evidence}/05-funding-fallback-preserves-preview.png`,fullPage:true});
  const invalidTopic=await page.request.post('/api/pathways/resources',{headers:{Origin:process.env.NEXTAUTH_URL!},data:{operationKey:crypto.randomUUID(),expectedPlanningRevision:state.profile.planningRevision,suggestionId:'direction-1',topicId:'invented-topic'}});
  expect(invalidTopic.status()).toBe(400);expect((await invalidTopic.json()).code).toBe('UNKNOWN_TOPIC');
  const blocked=await page.request.post('/api/roadmaps/generate',{headers:{Origin:process.env.NEXTAUTH_URL!},data:{operationKey:crypto.randomUUID(),expectedPlanningRevision:state.profile.planningRevision,expectedCatalogueVersion:catalogue.version,introductoryPlanAcknowledged:false}});
  expect(blocked.status()).toBe(409);expect((await blocked.json()).code).toBe('CONTENT_REVIEW_REQUIRED');
  const blockedGaps=await page.request.get('/api/gaps');expect(blockedGaps.status()).toBe(409);
  expect(await client.aIAttempt.count({where:{operation:{userId:user.id}}})).toBe(attempts);
  await page.getByRole('button',{name:'Learning roadmap',exact:true}).click();
  await expect(page.getByText('100%',{exact:true})).toBeVisible();await page.screenshot({path:`${evidence}/03-preserved-progress.png`,fullPage:true});
  const old=await client.roadmap.findUniqueOrThrow({where:{id:planId},include:{tasks:true}});expect(old.status).toBe('active');expect(old.tasks.every(task=>task.completed)).toBe(true);
 }finally{
  await client.user.deleteMany({where:{email}});await client.invitation.deleteMany({where:{email}});await client.fundingBudget.deleteMany({where:{id:budgetId}});await client.$disconnect();
 }
});
